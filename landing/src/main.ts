import './styles/main.css';
import { gsap } from 'gsap';
import { ScrollTrigger } from 'gsap/ScrollTrigger';
import { runLoader } from './modules/loader';
import { initHero } from './modules/hero';
import { initGenealogy } from './modules/genealogy';
import { initFailure } from './modules/failure';
import { initOps } from './modules/ops';
import { initPrivacy } from './modules/privacy';
import { initReveals } from './modules/reveal';
import { initNav } from './modules/nav';
import { initForm } from './modules/form';
import { initSections } from './modules/sections';
import { initPolish } from './modules/polish';
gsap.registerPlugin(ScrollTrigger);
const hero = initHero();
initGenealogy();
initOps();
initFailure();
initPrivacy();
initSections();
initPolish();
initReveals();
initNav();
initForm();
runLoader().then(() => {
    hero.intro();
    ScrollTrigger.refresh();
});
void hero.ready.then(() => ScrollTrigger.refresh());
void document.fonts.ready.then(() => ScrollTrigger.refresh());
